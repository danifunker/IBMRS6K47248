//============================================================================
//  IBMRS6K7248 - the planar's VPD/security EEPROM behind its controller (ISA 78-7C)
//
//  The firmware (EEPROM_* in the RAM image, v1.12) talks to a 93C46-class
//  serial EEPROM (64 words of 16 bits: "size code" 9; 10 and 11 would be 128
//  and 256 words) through a small controller with two register sets, chosen
//  by bit 3 of 7C (EEPROM_Use_Base_Ports / _Use_Alternate_Ports):
//
//    base set           78 w  command, low byte      79 w  command, high byte
//                       7A rw data, low byte         7B rw data, high byte
//    alternate set      78 rw the size code (9)      79 w  the lock boundary (EEPROM_lock)
//                       7B rw lock status (0: none; the firmware clears it)
//    both               7C r  status: bit 7 0, bit 6 and 4 "done", bit 5 ready, bit 3 the set
//                       7C w  bit 7 starts the command, bit 3 selects the set, the rest clears
//
//  The command word (EEPROM_Create_Command, then _Send_Command: high byte to
//  79, low byte to 78, then 7C bit 7) is the 93C46's: start bit and opcode in
//  bits 8-6 (110 READ, 101 WRITE, 111 ERASE, 100 with the address's top two
//  bits 11 EWEN, 00 EWDS, 10 ERAL, 01 WRAL), the word address in bits 5-0.
//  A READ leaves the word in 7B:7A; a WRITE takes it from there.
//  EEPROM_Wait polls 7C (bits 7-4 into CR7: mode 1 waits for bit 5, 2 and 3
//  for the done bits), with a timeout, so the controller answers at once.
//
//  The contents are an inference, not a dump (no real 7248's EEPROM is
//  available): word 0 is the CRC the firmware's talk_to_eeprom checks
//  (calc_non_lockable_crc over words 1-6 and 41-63, crcgen on each word's
//  high then low byte, init FFFF), words 41-48 the 16-character serial
//  number (GetEEPROMSerialNumber, check_EE_serial), the rest zero (no
//  passwords). The firmware writes its own error-check words (yo_eeprom), so
//  writes are honoured. firmware/tools/eeprom_image.py generates the image
//  between the markers below.
//============================================================================

module IBMRS6K7248_eeprom (
	input  logic        clk,
	input  logic        reset,
	input  logic        sel,          // one access this cycle
	input  logic        we,
	input  logic [2:0]  port,         // 78-7F -> 0-7
	input  logic [7:0]  wdata,
	output logic [7:0]  rdata         // the cycle after sel
);

logic [15:0] mem [64];                  // block RAM: one write a clock, read at addr
logic [15:0] cmd, data;
logic        alt, done, wen;
logic [7:0]  size_code, lock_bound, lock_status;

wire [2:0] op   = cmd[8:6];
wire [5:0] addr = cmd[5:0];

// the array's port: a word written (a command's, or ERAL's and WRAL's sweep, one word a clock),
// and the word at addr (the command register written a cycle or more before)
logic        m_we, sw_on;
logic [5:0]  m_a, sw_i;
logic [15:0] m_d, sw_d, m_q;
always_ff @(posedge clk) begin
	if (m_we) mem[m_a] <= m_d;
	else if (sw_on) mem[sw_i] <= sw_d;
	m_q <= mem[addr];
end

always_ff @(posedge clk) begin
	m_we <= 1'b0;
	if (sw_on && !m_we) begin
		sw_i <= sw_i + 6'd1;
		if (sw_i == 6'd63) sw_on <= 1'b0;
	end
	if (reset) begin
		cmd <= '0; data <= '0; alt <= 1'b0; done <= 1'b0; wen <= 1'b0; sw_on <= 1'b0;
		size_code <= 8'd9; lock_bound <= 8'd0; lock_status <= 8'd0;
	end
	else if (sel) begin
		if (we) begin
			case (port)
				3'd0: if (alt) size_code <= wdata; else cmd[7:0] <= wdata;
				3'd1: if (alt) lock_bound <= wdata; else cmd[15:8] <= wdata;
				3'd2: data[7:0] <= wdata;
				3'd3: if (alt) lock_status <= wdata; else data[15:8] <= wdata;
				3'd4: begin
					alt  <= wdata[3];
					done <= 1'b0;
					if (wdata[7]) begin
						done <= 1'b1;
						case (op)
							3'b110: data <= m_q;                                        // READ
							3'b101: if (wen) begin m_we <= 1'b1; m_a <= addr; m_d <= data; end        // WRITE
							3'b111: if (wen) begin m_we <= 1'b1; m_a <= addr; m_d <= 16'hFFFF; end     // ERASE
							3'b100: case (addr[5:4])                                     // EWEN, EWDS, ERAL, WRAL
								2'b11: wen <= 1'b1;
								2'b00: wen <= 1'b0;
								2'b10: if (wen) begin sw_on <= 1'b1; sw_i <= 6'd0; sw_d <= 16'hFFFF; end
								2'b01: if (wen) begin sw_on <= 1'b1; sw_i <= 6'd0; sw_d <= data; end
							endcase
							default: ;
						endcase
					end
				end
				default: ;
			endcase
		end
		case (port)
			3'd0: rdata <= alt ? size_code : cmd[7:0];
			3'd1: rdata <= alt ? lock_bound : cmd[15:8];
			3'd2: rdata <= data[7:0];
			3'd3: rdata <= alt ? lock_status : data[15:8];
			3'd4: rdata <= {1'b0, done, 1'b1, done, alt, 3'b000};
			default: rdata <= 8'h00;
		endcase
	end
end

initial begin
	for (int i = 0; i < 64; i++) mem[i] = 16'h0000;
	// EEPROM_IMAGE_BEGIN (generated by firmware/tools/eeprom_image.py; do not edit by hand)
	mem[0] = 16'h40C3;
	mem[41] = 16'h3030;
	mem[42] = 16'h3030;
	mem[43] = 16'h3030;
	mem[44] = 16'h3030;
	mem[45] = 16'h3030;
	mem[46] = 16'h3031;
	mem[47] = 16'h3233;
	mem[48] = 16'h3435;
	// EEPROM_IMAGE_END
end

endmodule
