# The PReP NVRAM (4 KB at ports 74/75/76) as the firmware's own formatter leaves it
# (NVRAMAccess's initialisation path, RAM 0x3A3D8-0x3A4D0, v1.12): the header the
# firmware's nvram_good accepts, an empty Global Environment area, an empty
# configuration area and an empty OS area, with the two CRCs. The firmware never
# formats a bad NVRAM at boot (nvraminit is the resident monitor's command), so
# the core starts with this image; the serial is the formatter's placeholder
# ('f' x 16: the firmware overwrites it from the EEPROM when that answers).
#
#   python3 nvram_image.py            prints the header
#   python3 nvram_image.py OUT.svh    writes the non-zero bytes as SystemVerilog assignments
#   python3 nvram_image.py OUT.bin    writes the 4 KB image
import sys, struct

SIZE = 4096
M = 0xFFFFFFFF
rotl = lambda x, n: ((x << n) | (x >> (32 - n))) & M

def crcgen(r3, b):                       # the firmware's crcgen (RAM 0x27570), bit for bit
    r0 = b & 0xff; r4 = rotl(r3, 8) & 0xFF00; r3 = r3 >> 8; r3 ^= r0
    r5 = ((r3 << 8) & M) >> 12; r6 = (r3 << 12) & M; r5 = (r6 | r5) & 0xF00F
    r4 = r3 | r4; r5 = r4 ^ r5
    r0 = rotl(r3, 1) & 0x1E0; r4 = rotl(r3, 5) & 0x1FE0; r4 ^= r5
    r3 = rotl(r3, 8) & 0xF000; return r4 ^ r3 ^ r0

def calc_crc(img, lo, hi):               # NVRAMCalcCRC: init FFFF, bytes lo..hi inclusive but never 4-7 (the CRCs); lo > hi gives FFFF
    v = 0xFFFF
    for a in range(lo, hi + 1):
        if 4 <= a < 8: continue
        v = crcgen(v, img[a]) & 0xFFFF
    return v

def image(time=0, date=0):
    n = bytearray(SIZE)
    def w32(o, v): n[o:o+4] = struct.pack('>I', v & M)
    def w16(o, v): n[o:o+2] = struct.pack('>H', v & 0xFFFF)
    w16(0x00, SIZE >> 10)                # Size in KB
    n[0x02] = 1                          # Version
    n[0x03] = 4                          # Revision
    n[0x08] = 1                          # LastOS
    n[0x09] = ord('B')                   # Endian
    for o in (0x34, 0x3C, 0x44, 0x4C, 0x54, 0x5C): w32(o, time)     # the error logs' times
    for o in (0x38, 0x40, 0x48, 0x50, 0x58, 0x60): w32(o, date)
    n[0x64:0x74] = b'f' * 16             # Serial, the placeholder
    ge_addr, ge_len = 0xF8, SIZE - 0x6F8                 # the Global Environment area: F8-9FF
    w32(0xC4, ge_addr); w32(0xC8, ge_len); w32(0xCC, time); w32(0xD0, date)
    w32(0xD4, SIZE); w32(0xD8, 0); w32(0xDC, time); w32(0xE0, date); w32(0xE4, 0)   # the configuration area: empty
    w32(0xE8, SIZE - 0x600); w32(0xEC, 0x200); w32(0xF0, time); w32(0xF4, date)    # the OS area: A00-BFF
    w16(0x06, calc_crc(n, SIZE, SIZE - 1))               # Crc2: the (empty) configuration area
    w16(0x04, calc_crc(n, 0, ge_addr + ge_len - 1))      # Crc1: the header and the GE area
    assert n[2] == 1 and n[3] == 4
    return n

if __name__ == '__main__':
    n = image()
    if len(sys.argv) > 1 and sys.argv[1].endswith('.bin'):
        open(sys.argv[1], 'wb').write(n)
    elif len(sys.argv) > 1:
        with open(sys.argv[1], 'w') as f:
            f.write('// generated by firmware/tools/nvram_image.py: the PReP NVRAM as the firmware formats it\n')
            for a, v in enumerate(n):
                if v: f.write('nvram[%d] = 8\'h%02X;\n' % (a, v))
    else:
        for o in range(0, 0xF8, 16): print('%02X: %s' % (o, n[o:o+16].hex(' ')))
        print('Crc1 %04X Crc2 %04X' % (struct.unpack('>H', n[4:6])[0], struct.unpack('>H', n[6:8])[0]))
