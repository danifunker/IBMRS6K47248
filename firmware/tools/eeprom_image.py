# The planar's VPD/security EEPROM (64 words of 16 bits behind the controller at ISA 78-7C,
# rtl/machine/IBMRS6K7248_eeprom.sv): an inferred image, since no real 7248's dump exists.
# What the firmware (v1.12) checks or reads:
#   word 0       the "non-lockable" CRC (talk_to_eeprom / calc_non_lockable_crc): crcgen over
#                words 1-6 and 41-63, each word's high byte then low byte, init FFFF
#   words 1-6    security state and passwords (yo_eeprom reads 1, 2, 7, 40; zero = none)
#   words 41-48  the 16-character serial number (GetEEPROMSerialNumber, check_EE_serial),
#                which build_vpd puts in the residual data's VPD.Serial
#
#   python3 eeprom_image.py                                     prints the image
#   python3 eeprom_image.py rtl/machine/IBMRS6K7248_eeprom.sv   rewrites the module's EEPROM_IMAGE section
import sys
from nvram_image import crcgen

SERIAL = b'0000000000012345'          # 16 digits; AIX shows it as the system id

def image(serial=SERIAL):
    w = [0] * 64
    assert len(serial) == 16
    for i in range(8):
        w[41 + i] = (serial[2 * i] << 8) | serial[2 * i + 1]
    crc = 0xFFFF
    for a in list(range(1, 7)) + list(range(41, 64)):
        crc = crcgen(crc, w[a] >> 8) & 0xFFFF
        crc = crcgen(crc, w[a] & 0xFF) & 0xFFFF
    w[0] = crc
    return w

BEGIN = '\t// EEPROM_IMAGE_BEGIN'
END = '\t// EEPROM_IMAGE_END'

if __name__ == '__main__':
    w = image()
    if len(sys.argv) > 1:
        p = sys.argv[1]; t = open(p, encoding='utf-8').read()
        a = t.index(BEGIN); b = t.index(END)
        body = ''.join("\tmem[%d] = 16'h%04X;\n" % (i, v) for i, v in enumerate(w) if v)
        t = t[:a] + BEGIN + ' (generated by firmware/tools/eeprom_image.py; do not edit by hand)\n' + body + t[b:]
        open(p, 'w', encoding='utf-8').write(t); print('rewrote', p, body.count('\n'), 'words')
    else:
        for o in range(0, 64, 8): print('%2d: %s' % (o, ' '.join('%04X' % v for v in w[o:o + 8])))
